import assert from 'node:assert/strict';
import {mkdtemp,writeFile,readFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {createServer} from 'node:http';
import {execFileSync} from 'node:child_process';
import {build} from 'vite';
import react from '@vitejs/plugin-react';
import {chromium} from 'playwright';
const root=process.cwd(),temp=await mkdtemp(path.join(tmpdir(),'fieldlance-recruitment-browser2415-')),dist=path.join(temp,'dist');
let server,browser;
try{
 await writeFile(path.join(temp,'index.html'),'<html><body><div id="root"></div><script type="module" src="'+path.join(root,'scripts/fixtures/recruitment2415/main.jsx')+'"></script></body></html>');
 await build({configFile:false,root:temp,publicDir:path.join(root,'public'),plugins:[{name:'fixture-transport',enforce:'pre',resolveId(id){if(id.endsWith('/supabase/client'))return path.join(root,'scripts/fixtures/recruitment2415/client.js');}},react()],resolve:{dedupe:['react','react-dom']},build:{outDir:dist,emptyOutDir:true},logLevel:'error'});
 server=createServer(async(req,res)=>{const url=new URL(req.url,'http://localhost');let file=url.pathname==='/'||url.pathname.startsWith('/app')?'/index.html':url.pathname;try{const body=await readFile(path.join(dist,file));res.setHeader('Content-Type',file.endsWith('.js')?'text/javascript':file.endsWith('.html')?'text/html':'application/octet-stream');res.end(body);}catch{res.writeHead(404);res.end('missing');}});
 await new Promise(r=>server.listen(0,'127.0.0.1',r));const origin='http://127.0.0.1:'+server.address().port;
 browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE}:{}),args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu']});
 const context=await browser.newContext({viewport:{width:390,height:844}}),page=await context.newPage(),errors=[];
 page.on('pageerror',e=>{errors.push(e.message);console.error('Browser error:',e.message)});page.setDefaultTimeout(10000);
 await page.goto(origin);
 await page.getByText('Consent fixture',{exact:true}).waitFor();
 await page.waitForTimeout(300);
 assert.equal(await page.getByRole('button',{name:'Start survey',exact:true}).count(),0);
 await page.goto(origin+'/?manager');
 await page.getByText('Collection access and history',{exact:true}).click();
 await page.getByText(/Historical access only: formal offer and worker acceptance required/).waitFor();
 assert.equal(await page.getByText('Direct survey access / operational override',{exact:true}).count(),0);
 assert.equal(await page.getByRole('button',{name:'Save scope / restore collection',exact:true}).count(),0);
 await page.getByRole('button',{name:'Open recruitment and offers',exact:true}).click();
 assert.equal(await page.evaluate(()=>window.recruitmentOpened),true);
 await page.goto(origin+'/?accepted');
 await page.getByRole('button',{name:'Start survey',exact:true}).waitFor();
 await page.reload();
 await page.getByRole('button',{name:'Start survey',exact:true}).waitFor();
 await page.goto(origin+'/?manager&accepted');
 await page.getByText('Collection access and history',{exact:true}).click();
 await page.getByRole('button',{name:'Save scope / restore collection',exact:true}).click();
 assert.deepEqual(await page.evaluate(()=>window.rpcCalls[0]),{name:'set_survey_assignment_scope',args:{p_project:'project',p_user:'worker',p_geography:'area',p_active:true}});
 assert.deepEqual(errors,[]);
 console.log('PASS Chromium 390px: legacy guidance, no bypass controls, recruitment navigation, accepted eligibility after reload, scope RPC wiring. Transport simulated; real HTTP tested separately.');
}finally{await browser?.close();if(server)await new Promise(r=>server.close(r));await rm(temp,{recursive:true,force:true});}
