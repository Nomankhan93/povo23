import assert from 'node:assert/strict';
import {mkdtemp,writeFile,readFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {createServer} from 'node:http';
import {execFileSync} from 'node:child_process';
import {build} from 'vite';
import react from '@vitejs/plugin-react';
import {chromium} from 'playwright';
const root=process.cwd(),temp=await mkdtemp(path.join(tmpdir(),'fieldlance-map-browser2411-')),dist=path.join(temp,'dist');
let server,browser;
try{
 await writeFile(path.join(temp,'index.html'),'<html><body><div id="root"></div><script type="module" src="'+path.join(root,'scripts/fixtures/map2411/main.jsx')+'"></script></body></html>');
 await build({configFile:false,root:temp,publicDir:path.join(root,'public'),plugins:[{name:'fixture-transport',enforce:'pre',resolveId(id){if(id.endsWith('/supabase/client'))return path.join(root,'scripts/fixtures/map2411/client.js');}},react()],resolve:{dedupe:['react','react-dom']},build:{outDir:dist,emptyOutDir:true},logLevel:'error'});
 server=createServer(async(req,res)=>{const url=new URL(req.url,'http://localhost');let file=url.pathname==='/'||url.pathname.startsWith('/app')?'/index.html':url.pathname;try{const body=await readFile(path.join(dist,file));res.setHeader('Content-Type',file.endsWith('.js')?'text/javascript':file.endsWith('.html')?'text/html':'application/octet-stream');res.end(body);}catch{res.writeHead(404);res.end('missing');}});
 await new Promise(r=>server.listen(0,'127.0.0.1',r));const origin='http://127.0.0.1:'+server.address().port;
 browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE}:{}),args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu']});
 const context=await browser.newContext(),page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
 page.setDefaultTimeout(10000);
 await page.route('https://unpkg.com/**',route=>route.abort());
 await page.goto(origin);
 await page.getByText('Basemap unavailable',{exact:true}).waitFor();
 await page.getByText('Evidence 1',{exact:true}).waitFor();
 assert.equal(await page.getByRole('listitem').count(),1);
 console.log('PASS Chromium renderer failure preserves accessible evidence and load-more');
 await page.getByRole('combobox',{name:/^Field Worker/}).selectOption('alice');
 await page.getByRole('combobox',{name:/^Status/}).selectOption('submitted');
 await page.getByLabel('Check-outs',{exact:true}).uncheck();
 await page.getByRole('button',{name:/Load more evidence/}).click();
 await page.getByText('Evidence 2',{exact:true}).waitFor();
 await page.getByRole('listitem').filter({hasText:'Evidence 2'}).getByRole('button',{name:'Open survey response',exact:true}).click();
 await page.getByText('Selected source: response-2',{exact:true}).waitFor();
 await page.evaluate(()=>window.mapCalls=[]);
 await page.getByRole('button',{name:'Back to map',exact:true}).click();
 await page.locator('[data-selected="true"]').filter({hasText:'Evidence 2'}).waitFor();
 assert.equal(await page.getByRole('combobox',{name:/^Field Worker/}).inputValue(),'alice');
 assert.equal(await page.getByRole('combobox',{name:/^Status/}).inputValue(),'submitted');
 assert.equal(await page.getByLabel('Check-outs',{exact:true}).isChecked(),false);
 assert.equal(await page.locator('[data-selected="true"]').count(),1);
 assert.match(await page.locator('[data-selected="true"]').innerText(),/Evidence 2/);
 const calls=await page.evaluate(()=>window.mapCalls);
 assert.ok(calls.some(c=>c.p_cursor_id==='survey:1'));
 assert.ok(calls.every(c=>c.p_worker==='alice'&&c.p_status==='submitted'&&!c.p_layers.includes('attendance_check_out')));
 console.log('PASS Chromium StrictMode remount restores filters, selected source and pages through fresh RPCs');
 await page.getByRole('button',{name:'Open survey response',exact:true}).first().click();
 await page.evaluate(()=>window.denyMap=true);
 await page.getByRole('button',{name:'Back to map',exact:true}).click();
 await page.getByRole('alert').filter({hasText:'Your access has changed or this action is no longer available'}).waitFor();
 assert.equal(await page.getByRole('listitem').count(),0);
 console.log('PASS Chromium revoked access on return shows error without stale cached evidence');
 await page.evaluate(()=>window.denyMap=false);
 await page.getByRole('button',{name:'Switch owner',exact:true}).click();
 await page.getByText('Evidence 1',{exact:true}).waitFor();
 assert.equal(await page.getByRole('combobox',{name:/^Field Worker/}).inputValue(),'');
 assert.equal(await page.getByRole('combobox',{name:/^Status/}).inputValue(),'');
 assert.equal(await page.getByLabel('Check-outs',{exact:true}).isChecked(),true);
 assert.equal(await page.getByRole('listitem').count(),1);
 assert.deepEqual(errors,[]);
 console.log('PASS Chromium owner-separated map view state');
 console.log('Map RPC transport simulated; actual map component and browser DOM exercised.');
}finally{await browser?.close();if(server)await new Promise(r=>server.close(r));await rm(temp,{recursive:true,force:true});}
